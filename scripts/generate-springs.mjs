// Bakes Motion (motion.dev) springs into CSS `linear()` easings, so hover
// animations run on the compositor with no JavaScript at runtime.
// Run `npm run springs` after changing a spring below.
import { writeFileSync } from "node:fs";
import { spring } from "motion";

const SPRINGS = {
  // Row hover: quick and settled, no overshoot.
  hover: { visualDuration: 0.22, bounce: 0 },
  // Small controls (star, checkbox, row icons): a little life.
  pop: { visualDuration: 0.3, bounce: 0.35 },
  // Floating compose button.
  fab: { visualDuration: 0.35, bounce: 0.4 },
  // Slide-over menu: no bounce, so it never overshoots past the window edge.
  panel: { visualDuration: 0.3, bounce: 0 },
  // Views (inbox, open email) settling in when they appear.
  enter: { visualDuration: 0.32, bounce: 0.12 },
};

const lines = Object.entries(SPRINGS).map(([name, options]) => {
  // String(spring) is "<duration>ms linear(...)"
  const [duration, ...easing] = String(spring({ keyframes: [0, 1], ...options })).split(" ");
  return `  --sg-spring-${name}-duration: ${duration};\n  --sg-spring-${name}: ${easing.join(" ")};`;
});

writeFileSync(
  new URL("../springs.css", import.meta.url),
  `/* Generated by scripts/generate-springs.mjs from Motion springs. Do not edit. */\nhtml.sg-on {\n${lines.join("\n")}\n}\n`
);
console.log("springs.css written");
